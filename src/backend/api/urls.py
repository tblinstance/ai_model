"""URL routes for Django API gateway, conversations, and neural training endpoints."""

from django.urls import path

from .views import (
    AccountVerifyView,
    AnalyticsOverviewView,
    ConversationDetailView,
    ConversationListCreateView,
    DashboardOverviewView,
    GatewayAudioAnalyzeView,
    GatewayAudioTranscribeView,
    GatewayGenerateView,
    GatewayHealthView,
    GatewayModelsView,
    GatewayRagScrapeView,
    GatewayTrainAllView,
    GatewayTrainCheckpointsView,
    GatewayTrainEvaluateView,
    GatewayTrainResetView,
    GatewayTrainView,
    ProfileListView,
    ProfileMeView,
    SecretKeyDetailView,
    SecretKeyListCreateView,
    TrainingRunHistoryView,
    TrainingSampleDetailView,
    TrainingSampleListCreateView,
    api_root_router,
)

urlpatterns = [
    path("", api_root_router, name="gateway-api-root"),
    path("health/", GatewayHealthView.as_view(), name="gateway-health"),
    path("models/", GatewayModelsView.as_view(), name="gateway-models"),
    path("dashboard/", DashboardOverviewView.as_view(), name="gateway-dashboard"),
    path("verify/", AccountVerifyView.as_view(), name="account-verify"),
    path("analytics/", AnalyticsOverviewView.as_view(), name="gateway-analytics"),
    path("profile/", ProfileMeView.as_view(), name="profile-me"),
    path("profiles/", ProfileListView.as_view(), name="profile-list"),
    path("keys/", SecretKeyListCreateView.as_view(), name="secret-key-list"),
    path("keys/<int:pk>/", SecretKeyDetailView.as_view(), name="secret-key-detail"),
    path("api-keys/", SecretKeyListCreateView.as_view(), name="api-key-list"),
    path("api-keys/<int:pk>/", SecretKeyDetailView.as_view(), name="api-key-detail"),
    path("conversations/", ConversationListCreateView.as_view(), name="conversation-list"),
    path("conversations/<int:pk>/", ConversationDetailView.as_view(), name="conversation-detail"),
    path("train/", GatewayTrainView.as_view(), name="gateway-train"),
    path("train/all/", GatewayTrainAllView.as_view(), name="gateway-train-all"),
    path("train/samples/", TrainingSampleListCreateView.as_view(), name="training-sample-list"),
    path("train/samples/<int:pk>/", TrainingSampleDetailView.as_view(), name="training-sample-detail"),
    path("train/history/", TrainingRunHistoryView.as_view(), name="training-history"),
    path("train/evaluate/", GatewayTrainEvaluateView.as_view(), name="gateway-train-evaluate"),
    path("train/checkpoints/", GatewayTrainCheckpointsView.as_view(), name="gateway-train-checkpoints"),
    path("train/reset/", GatewayTrainResetView.as_view(), name="gateway-train-reset"),
    path("audio/transcribe/", GatewayAudioTranscribeView.as_view(), name="gateway-audio-transcribe"),
    path("audio/analyze/", GatewayAudioAnalyzeView.as_view(), name="gateway-audio-analyze"),
    path("rag/scrape/", GatewayRagScrapeView.as_view(), name="gateway-rag-scrape"),
    path("generate/<str:task>/", GatewayGenerateView.as_view(), name="gateway-generate"),
]
